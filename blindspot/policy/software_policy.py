"""
Software install policy: which versions may be installed and run.

Owner: D

Public interface:
    generate_software_policy(software_rows, catalog) -> dict
    render_applocker(policy, enforce=False) -> str   (AppLocker XML)

The JSON is the decision list (for Intune / SCCM / a self-service portal):
per approved product, the lowest version that may be installed, and every
installed version that is blocked with its reason. It updates by itself when an
advisory arrives or a fixed version is released.

The AppLocker XML turns that into Windows rules for products whose installer
is code-signed: an Allow publisher rule from the lowest safe version upwards,
for both executables and MSI installers. Older, vulnerable versions then match
no Allow rule. It is generated in AuditOnly mode: merge it into the existing
policy (Set-AppLockerPolicy -Merge) and check the audit log before enforcing.
For products without a publisher signature, AppLocker needs a hash rule from the
real installer; the XML lists them as comments with the PowerShell command.
"""
from __future__ import annotations

import uuid
from xml.sax.saxutils import quoteattr

from blindspot.contract import now_iso
from blindspot.software.assess import version_key

NAMESPACE = uuid.UUID("6f1d3b1e-6b42-4c55-9a3f-0b1d5e7a9c11")


def _four_part(version: str) -> str:
    parts = list(version_key(version))[:4]
    return ".".join(str(p) for p in parts + [0] * (4 - len(parts)))


def generate_software_policy(software_rows: list[dict], catalog: dict) -> dict:
    rules = []
    for entry in catalog.get("approved", []):
        hits = [s for s in software_rows if s.get("catalog_name") == entry["name"]]
        blocked = [s for s in hits if s["status"] == "blocked"]
        allowed_from = max([entry.get("approved_version") or "0"]
                           + [s["fixed_in"] for s in blocked if s.get("fixed_in")], key=version_key)
        rules.append({
            "product": entry["name"], "publisher": entry.get("publisher", ""),
            "signer": entry.get("signer"), "product_name": entry.get("product"),
            "allowed_from": allowed_from,
            "blocked_versions": [{"version": s["version"], "machines": s.get("machines", 1),
                                  "reason": "; ".join(s["reasons"]),
                                  "cves": [v["cve"] for v in s["vulnerabilities"]]} for s in blocked],
        })
    review = [{"name": s["name"], "version": s["version"], "reason": "; ".join(s["reasons"])}
              for s in software_rows if s["status"] == "review"]
    return {
        "generated_at": now_iso(),
        "block_at_decision": catalog.get("block_at_decision", "Attend"),
        "rules": rules,
        "needs_review": review,
    }


def render_applocker(policy: dict, enforce: bool = False) -> str:
    mode = "Enabled" if enforce else "AuditOnly"
    signed = [r for r in policy["rules"] if r.get("signer") and r.get("product_name")]
    unsigned = [r for r in policy["rules"] if not (r.get("signer") and r.get("product_name"))]
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- Generated by Blindspot {policy['generated_at']}. AuditOnly by default: merge with",
             "     Set-AppLockerPolicy -XmlPolicy blindspot_applocker.xml -Merge and review the audit log",
             "     (Event Viewer > AppLocker) before switching EnforcementMode to Enabled. -->",
             '<AppLockerPolicy Version="1">']
    for collection in ("Exe", "Msi"):
        lines.append(f'  <RuleCollection Type="{collection}" EnforcementMode="{mode}">')
        for r in signed:
            rid = uuid.uuid5(NAMESPACE, f"{collection}:{r['product']}:{r['allowed_from']}")
            desc = f"Blindspot: {r['product']} {r['allowed_from']} and later"
            if r["blocked_versions"]:
                desc += "; older versions blocked: " + ", ".join(b["reason"] for b in r["blocked_versions"])
            lines += [
                f'    <FilePublisherRule Id="{rid}" Name={quoteattr(r["product"] + " (approved versions)")} '
                f'Description={quoteattr(desc[:250])} UserOrGroupSid="S-1-1-0" Action="Allow">',
                "      <Conditions>",
                f'        <FilePublisherCondition PublisherName={quoteattr(r["signer"])} '
                f'ProductName={quoteattr(r["product_name"])} BinaryName="*">',
                f'          <BinaryVersionRange LowSection="{_four_part(r["allowed_from"])}" HighSection="*" />',
                "        </FilePublisherCondition>",
                "      </Conditions>",
                "    </FilePublisherRule>",
            ]
        lines.append("  </RuleCollection>")
    for r in unsigned:
        if r["blocked_versions"]:
            versions = ", ".join(b["version"] for b in r["blocked_versions"])
            lines.append(f"  <!-- {r['product']}: no publisher signature recorded. Blocked versions: {versions}. "
                         "Create hash rules from the real files: Get-AppLockerFileInformation -Path <installer> | "
                         "New-AppLockerPolicy -RuleType Hash -User Everyone -Xml -->")
    lines.append("</AppLockerPolicy>")
    return "\n".join(lines) + "\n"
